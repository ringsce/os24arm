/**
 * @brief Initialize framebuffer
 */
void fb_init(void)
{
    fb_init_driver();
    kprintf("[FB] Framebuffer initialized: %dx%d\r\n", fb_get_width(), fb_get_height());
}

/**
 * @brief Clear entire screen
 */
void fb_clear(fb_color_t color)
{
    fb_clear_screen(color);
}

/**
 * @brief Put a single pixel
 */
void fb_putpixel(int x, int y, fb_color_t color)
{
    fb_set_pixel(x, y, color);
}

/**
 * @brief Fill a rectangle
 */
void fb_fillrect(const fb_rect_t *rect, fb_color_t color)
{
    fb_fill_rect(rect->x, rect->y, rect->width, rect->height, color);
}

/**
 * @brief Look up the 8x8 glyph bitmap for a character
 *
 * Exposed so client-side code can render text into its own off-screen
 * buffer (e.g. a Wayland-style surface) without duplicating the font table.
 */
const uint8_t *fb_get_glyph(char c)
{
    unsigned char idx = (unsigned char)c;
    if (idx >= 128) idx = ' ';
    return font_8x8[idx];
}

/**
 * @brief Draw a string
 */
void fb_drawstring(int x, int y, const char *str, fb_color_t fg, fb_color_t bg)
{
    int cx = x;
    int cy = y;

    while (*str) {
        const uint8_t *glyph = font_8x8[(unsigned char)*str];

        /* Draw character */
        for (int row = 0; row < 8; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (bits & (1 << (7 - col))) {
                    fb_set_pixel(cx + col, cy + row, fg);
                } else {
                    fb_set_pixel(cx + col, cy + row, bg);
                }
            }
        }

        cx += 8;
        str++;
    }
}

/**
 * @brief Draw a button
 */
void fb_draw_button(const fb_rect_t *rect, const char *text, bool pressed)
{
    /* Button background */
    fb_color_t bg_color = pressed ? FB_COLOR(160, 160, 160) : FB_COLOR(192, 192, 192);
    fb_fillrect(rect, bg_color);

    /* Border */
    fb_color_t light = FB_COLOR(255, 255, 255);
    fb_color_t dark = FB_COLOR(64, 64, 64);

    /* Top and left - light when not pressed, dark when pressed */
    fb_color_t top_left = pressed ? dark : light;
    fb_color_t bottom_right = pressed ? light : dark;

    /* Draw borders */
    for (int i = 0; i < rect->width; i++) {
        fb_set_pixel(rect->x + i, rect->y, top_left);
        fb_set_pixel(rect->x + i, rect->y + rect->height - 1, bottom_right);
    }
    for (int i = 0; i < rect->height; i++) {
        fb_set_pixel(rect->x, rect->y + i, top_left);
        fb_set_pixel(rect->x + rect->width - 1, rect->y + i, bottom_right);
    }

    /* Center text */
    int text_len = 0;
    while (text[text_len]) text_len++;
    int text_x = rect->x + (rect->width - text_len * 8) / 2;
    int text_y = rect->y + (rect->height - 8) / 2;

    fb_drawstring(text_x, text_y, text, WPS_TEXT_BLACK, bg_color);
}

/**
 * @brief Draw a title bar
 */
void fb_draw_titlebar(const fb_rect_t *rect, const char *title, bool active)
{
    /* Title bar background */
    fb_color_t bg_color = active ? WPS_TITLEBAR_ACTIVE : FB_COLOR(128, 128, 128);
    fb_fillrect(rect, bg_color);

    /* Draw title text */
    fb_drawstring(rect->x + 8, rect->y + 8, title, WPS_TEXT_WHITE, bg_color);
}

/**
 * @brief Get framebuffer width
 */
int fb_get_width(void)
{
    return fb_width();
}

/**
 * @brief Get framebuffer height
 */
int fb_get_height(void)
{
    return fb_height();
}